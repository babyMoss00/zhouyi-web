// 计算日干支（以1900年1月31日为甲子日基准）
function getDayGanzhi(date) {
    const base = new Date(1900, 0, 31);
    const diff = Math.floor((date.getTime() - base.getTime()) / (24 * 60 * 60 * 1000));
    const gan = TIANGAN[((diff % 10) + 10) % 10];
    const zhi = DIZHI[((diff % 12) + 12) % 12];
    return gan + zhi;
}

function getLiuqin(myWuxing, targetWuxing) {
    const mi = WUXING_ORDER.indexOf(myWuxing);
    const ti = WUXING_ORDER.indexOf(targetWuxing);
    if (mi === -1 || ti === -1) return "?";
    const diff = (ti - mi + 5) % 5;
    return LIUQIN_NAMES[diff];
}
